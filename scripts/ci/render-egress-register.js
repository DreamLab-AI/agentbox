#!/usr/bin/env node
/**
 * render-egress-register.js — the N-7 prompt egress register, rendered from its one source.
 *
 * `config/egress-policy.json` `.register` is the machine record: one row per route by which a
 * prompt, code, a secret-adjacent string or a key can leave the container. This script renders
 * that record into `docs/SECURITY-profiles.md` between the two markers below, so the table a
 * reviewer reads and the record a tool reads cannot drift apart.
 *
 *   node scripts/ci/render-egress-register.js           rewrite the table in place
 *   node scripts/ci/render-egress-register.js --check   exit 1 if the file differs from a fresh
 *                                                       render, or the record is malformed
 *
 * --check also validates the record itself:
 *   - every row carries the required fields, a known `leaves` class and a known destination class;
 *   - a row whose gate begins "none" carries the `no-gate` marker, and a row whose accepted-egress
 *     record begins "none" carries `no-accepted-record` (a gap is marked, never implied);
 *   - every backticked `path:line` or `path:line-line` citation names a file that exists in the
 *     checkout and a line range inside it. A citation whose file shrank below the cited line is
 *     stale and must be re-verified against `register.verified_commit`.
 *
 * Exit codes: 0 in sync and valid; 1 drift or validation errors; 2 usage or I/O error.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const POLICY = path.join(ROOT, 'config', 'egress-policy.json');
const BEGIN = '<!-- egress-register:begin (generated by scripts/ci/render-egress-register.js from config/egress-policy.json; do not edit by hand) -->';
const END = '<!-- egress-register:end -->';
const REQUIRED = ['id', 'route', 'leaves', 'destination_class', 'destination', 'gate', 'accepted_egress', 'markers', 'notes'];
const CITE = /`([A-Za-z0-9_.\/-]+\.[A-Za-z][A-Za-z0-9]*):(\d+)(?:-(\d+))?`/g;

/** Escape a table cell: pipes split columns and newlines end rows. */
function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

/** Render the generated block (markers included) from the register object. */
function render(reg) {
  const markerLabel = { 'no-gate': 'no gate', 'no-accepted-record': 'no accepted record' };
  const lines = [
    BEGIN,
    '',
    `Source: [\`config/egress-policy.json\`](../config/egress-policy.json) \`.register\`. ` +
      `Citations verified at \`${reg.verified_commit.slice(0, 9)}\` on ${reg.verified_on}. ` +
      `${reg.routes.length} routes.`,
    '',
    reg.scope,
    '',
    reg.credential_class,
    '',
    '| id | Route | What leaves | Destination class | Gate | Accepted-egress record | Notes |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const r of reg.routes) {
    const flags = r.markers.map((m) => `**[marker: ${markerLabel[m] || m}]**`).join(' ');
    lines.push('| ' + [
      `\`${r.id}\``,
      r.route,
      r.leaves.join(', '),
      `${r.destination_class}: ${r.destination}`,
      r.gate,
      r.accepted_egress,
      flags ? `${flags} ${r.notes}` : r.notes,
    ].map(cell).join(' | ') + ' |');
  }
  const gateless = reg.routes.filter((r) => r.markers.includes('no-gate')).map((r) => `\`${r.id}\``);
  const unrecorded = reg.routes.filter((r) => r.markers.includes('no-accepted-record')).map((r) => `\`${r.id}\``);
  lines.push(
    '',
    `Marked with no gate (${gateless.length}): ${gateless.join(', ') || 'none'}.`,
    '',
    `Marked with no accepted-egress record (${unrecorded.length}): ${unrecorded.join(', ') || 'none'}.`,
    '',
    END,
  );
  return lines.join('\n');
}

/** Structural and citation checks; returns a list of error strings. */
function validate(reg) {
  const errors = [];
  for (const k of ['verified_commit', 'verified_on', 'rendered_to', 'scope', 'credential_class', 'routes']) {
    if (reg[k] === undefined) errors.push(`register.${k} missing`);
  }
  if (!Array.isArray(reg.routes) || reg.routes.length === 0) return errors.concat('register.routes empty');
  const ids = new Set();
  for (const r of reg.routes) {
    const where = `route ${r.id || '(no id)'}`;
    for (const f of REQUIRED) if (r[f] === undefined || r[f] === '') errors.push(`${where}: ${f} missing`);
    if (ids.has(r.id)) errors.push(`${where}: duplicate id`);
    ids.add(r.id);
    for (const l of r.leaves || []) {
      if (!reg.leaves_vocabulary.includes(l)) errors.push(`${where}: unknown leaves class "${l}"`);
    }
    if (!reg.destination_classes.includes(r.destination_class)) {
      errors.push(`${where}: unknown destination class "${r.destination_class}"`);
    }
    for (const m of r.markers || []) {
      if (!Object.prototype.hasOwnProperty.call(reg.marker_vocabulary, m)) errors.push(`${where}: unknown marker "${m}"`);
    }
    if (/^none\b/i.test(r.gate) && !r.markers.includes('no-gate')) errors.push(`${where}: gate is none but no-gate marker absent`);
    if (/^none\b/i.test(r.accepted_egress) && !r.markers.includes('no-accepted-record')) {
      errors.push(`${where}: accepted-egress is none but no-accepted-record marker absent`);
    }
    for (const field of ['destination', 'gate', 'accepted_egress', 'notes']) {
      for (const m of String(r[field] || '').matchAll(CITE)) {
        const [, rel, a, b] = m;
        const abs = path.join(ROOT, rel);
        if (!fs.existsSync(abs)) { errors.push(`${where}: cites missing file ${rel}`); continue; }
        const count = fs.readFileSync(abs, 'utf8').split('\n').length;
        const hi = Number(b || a);
        if (Number(a) < 1 || hi < Number(a) || hi > count) {
          errors.push(`${where}: ${rel}:${a}${b ? '-' + b : ''} outside the file (${count} lines); re-verify`);
        }
      }
    }
  }
  return errors;
}

/** Replace the marked block in `text`, or append it under a register heading. */
function splice(text, block) {
  const i = text.indexOf(BEGIN);
  const j = text.indexOf(END);
  if (i === -1 && j === -1) return null;
  if (i === -1 || j === -1 || j < i) throw new Error('register markers are unbalanced');
  return text.slice(0, i) + block + text.slice(j + END.length);
}

function main(argv) {
  const check = argv.includes('--check');
  let doc;
  try {
    doc = JSON.parse(fs.readFileSync(POLICY, 'utf8'));
  } catch (e) {
    process.stderr.write(`render-egress-register: cannot read ${POLICY}: ${e.message}\n`);
    return 2;
  }
  const reg = doc.register;
  if (!reg) { process.stderr.write('render-egress-register: config/egress-policy.json has no .register\n'); return 2; }
  const target = path.join(ROOT, reg.rendered_to || 'docs/SECURITY-profiles.md');
  const errors = validate(reg);
  const block = render(reg);
  const current = fs.readFileSync(target, 'utf8');
  const next = splice(current, block);
  if (check) {
    if (next === null) errors.push(`${path.relative(ROOT, target)} has no egress-register markers`);
    else if (next !== current) {
      errors.push(`${path.relative(ROOT, target)} is out of date: run node scripts/ci/render-egress-register.js`);
    }
    for (const e of errors) process.stderr.write(`render-egress-register: ${e}\n`);
    if (errors.length) return 1;
    process.stdout.write(`render-egress-register: ${reg.routes.length} routes in sync and valid\n`);
    return 0;
  }
  if (errors.length) {
    for (const e of errors) process.stderr.write(`render-egress-register: ${e}\n`);
    return 1;
  }
  const out = next === null
    ? current.replace(/\s*$/, '\n') + `\n## Prompt egress register — ${reg.verified_on}\n\n${block}\n`
    : next;
  fs.writeFileSync(target, out);
  process.stdout.write(`render-egress-register: wrote ${reg.routes.length} routes to ${path.relative(ROOT, target)}\n`);
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { render, validate, splice, BEGIN, END };
