#[test]
fn an_unparseable_pdf_fails_closed_and_writes_nothing() {
    // Replaces the old "always produces an output file and a mode" test. A
    // degraded result is not a clean: a byte-level edit cannot reach /Info and
    // leaves /Length values and cross-reference offsets pointing at the wrong
    // places, and a straight copy retains everything. Both used to return Ok.
    let dir = tempfile::tempdir().unwrap();
    let source = dir.path().join("in.pdf");
    let dest = dir.path().join("out.pdf");
    let pdf = pdf_blob(b"1 0 obj<</Producer(Generated by OpenAI)>>endobj", b"bytes");
    std::fs::write(&source, &pdf).unwrap();

    let error = clean_pdf(&source, &dest).unwrap_err();
    assert!(
        error.contains("cannot build a complete object graph"),
        "error was {error}"
    );
    assert!(error.contains("nothing was written"));
    assert!(!dest.exists(), "no destination may be created on failure");
}

#[test]
fn an_unparseable_pdf_with_an_xmp_packet_is_refused_rather_than_regex_edited() {
    let dir = tempfile::tempdir().unwrap();
    let source = dir.path().join("in.pdf");
    let dest = dir.path().join("out.pdf");
    let mut pdf = pdf_blob(b"1 0 obj<< /Length 123 /Type /Metadata >>endobj", b"bytes");
    pdf.extend_from_slice(XMP);
    std::fs::write(&source, &pdf).unwrap();

    assert!(clean_pdf(&source, &dest).is_err());
    assert!(!dest.exists());
}

#[test]
fn a_parseable_pdf_takes_the_object_graph_rewrite() {
    let dir = tempfile::tempdir().unwrap();
    let source = dir.path().join("in.pdf");
    let dest = dir.path().join("out.pdf");
    std::fs::write(&source, real_pdf("Ada Lovelace")).unwrap();

    let (actions, meta) = clean_pdf(&source, &dest).unwrap();
    assert_eq!(meta["mode"], serde_json::json!("lopdf"));
    assert_eq!(meta["structural_rewrite"], serde_json::json!(true));
    assert_eq!(meta["verified"], serde_json::json!(true));
    assert!(actions.contains(&"remove trailer /Info".to_string()));
    assert!(actions.contains(&"remove catalog /Metadata".to_string()));

    let cleaned = std::fs::read(&dest).unwrap();
    assert!(!contains(&cleaned, b"Ada Lovelace"));
    assert!(!contains(&cleaned, b"Generated by Claude"));
    assert!(!contains(&cleaned, b"xpacket"));
    // Still a document: it reloads and keeps its single page.
    let reloaded = Document::load_mem(&cleaned).expect("the output is a valid PDF");
    assert_eq!(reloaded.get_pages().len(), 1);
    assert!(reloaded.trailer.get(b"Info").is_err());
}

#[test]
fn an_incremental_update_cannot_resurrect_the_superseded_metadata() {
    let dir = tempfile::tempdir().unwrap();
    let source = dir.path().join("incremental.pdf");
    let dest = dir.path().join("out.pdf");
    let pdf = pdf_with_incremental_metadata("Ada Lovelace", "Claude");
    std::fs::write(&source, &pdf).unwrap();

    let (_, meta) = clean_pdf(&source, &dest).unwrap();
    assert_eq!(meta["structural_rewrite"], serde_json::json!(true));

    let cleaned = std::fs::read(&dest).unwrap();
    // Neither revision's author survives anywhere in the output byte stream.
    assert!(
        !contains(&cleaned, b"Ada Lovelace"),
        "the superseded /Info must not survive the rewrite"
    );
    assert!(!contains(&cleaned, b"Claude"));
    assert!(!contains(&cleaned, b"xpacket"));
    assert_eq!(
        Document::load_mem(&cleaned)
            .expect("the output is a valid PDF")
            .get_pages()
            .len(),
        1
    );
}

/// A PDF carrying its C2PA manifest the way the specification says: an embedded
/// file specification with `/AFRelationship /C2PA_Manifest`, referenced from the
/// catalogue's `/AF` array.
fn pdf_with_c2pa_embedded_file() -> Vec<u8> {
    let mut doc = Document::with_version("1.7");
    let pages_id = doc.new_object_id();
    let page_id = doc.add_object(dictionary! {
        "Type" => "Page",
        "Parent" => pages_id,
        "MediaBox" => vec![0.into(), 0.into(), 200.into(), 200.into()],
    });
    doc.set_object(
        pages_id,
        dictionary! { "Type" => "Pages", "Kids" => vec![page_id.into()], "Count" => 1 },
    );
    let manifest_id = doc.add_object(Stream::new(
        dictionary! { "Type" => "EmbeddedFile" },
        b"jumb c2pa manifest store".to_vec(),
    ));
    let spec_id = doc.add_object(dictionary! {
        "Type" => "Filespec",
        "F" => Object::string_literal("c2pa.c2pa"),
        "AFRelationship" => "C2PA_Manifest",
        "EF" => dictionary! { "F" => manifest_id },
    });
    let catalog_id = doc.add_object(dictionary! {
        "Type" => "Catalog",
        "Pages" => pages_id,
        "AF" => vec![spec_id.into()],
    });
    doc.trailer.set("Root", catalog_id);

    let mut out = Vec::new();
    doc.save_to(&mut out).expect("the fixture serialises");
    out
}

#[test]
fn a_c2pa_embedded_file_specification_is_removed_with_its_stream() {
    let dir = tempfile::tempdir().unwrap();
    let source = dir.path().join("c2pa.pdf");
    let dest = dir.path().join("out.pdf");
    let pdf = pdf_with_c2pa_embedded_file();
    assert!(contains(&pdf, b"C2PA_Manifest"));
    std::fs::write(&source, &pdf).unwrap();

    let (actions, _) = clean_pdf(&source, &dest).unwrap();
    assert!(
        actions
            .iter()
            .any(|a| a.starts_with("drop C2PA embedded-file specification")),
        "actions were {actions:?}"
    );
    let cleaned = std::fs::read(&dest).unwrap();
    assert!(!contains(&cleaned, b"C2PA_Manifest"));
    assert!(!contains(&cleaned, b"jumb c2pa manifest store"));
    assert_eq!(
        Document::load_mem(&cleaned)
            .expect("the output is a valid PDF")
            .get_pages()
            .len(),
        1
    );
}

#[test]
fn every_written_output_has_been_verified() {
    let dir = tempfile::tempdir().unwrap();
    let source = dir.path().join("in.pdf");
    let dest = dir.path().join("out.pdf");
    std::fs::write(&source, real_pdf("Ada Lovelace")).unwrap();

    let (actions, _) = clean_pdf(&source, &dest).unwrap();
    assert!(actions
        .iter()
        .any(|a| a.starts_with("verified: the output reparses")));

    // The verification is a real gate, not a label: it rejects a document that
    // still carries a metadata carrier.
    let mut doc = Document::load_mem(&real_pdf("Ada Lovelace")).unwrap();
    let mut untouched = Vec::new();
    doc.save_to(&mut untouched).unwrap();
    assert!(verify(&untouched).is_err(), "an unscrubbed PDF must fail");
}
